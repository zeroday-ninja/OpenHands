import {
  WORKBENCH_DOCUMENT_VERSION,
  type WorkbenchDocument,
  type WorkbenchPart,
  type WorkbenchWire,
  type WorkbenchWireLabel,
} from "#/types/workbench";

type PartSeed = Omit<WorkbenchPart, "repoId" | "files" | "changes"> & {
  files?: string[];
  changes?: number;
};

function parts(repoId: string, seeds: PartSeed[]): WorkbenchPart[] {
  return seeds.map((seed) => ({
    files: [],
    changes: 0,
    ...seed,
    repoId,
  }));
}

function wires(
  triples: [string, string, WorkbenchWireLabel][],
): WorkbenchWire[] {
  return triples.map(([from, to, label]) => ({
    id: `${from}->${to}`,
    from,
    to,
    label,
  }));
}

